// Generates migrations/0004_seed_catalogue.sql from catalogue-data.mjs.
//
// The catalogue is written as structured data and rendered to SQL rather than
// hand-typed, so 130-odd programmes stay consistent and reviewable. Re-run with:
//   node scripts/generate-catalogue-seed.mjs
//
// The migration uses INSERT OR IGNORE against deterministic ids, so re-applying
// it never duplicates rows and never overwrites a Super Admin's later edits.

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { areas, areaFaculty, faculty, programmeTypes } from './catalogue-data.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'migrations', '0004_seed_catalogue.sql');

const q = (value) => {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return String(value);
  return `'${String(value).replaceAll("'", "''")}'`;
};

/** Stable, readable primary keys so re-running the seed is idempotent. */
const slugify = (text) =>
  text
    .toLowerCase()
    .replaceAll('&', ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 80);

const typeBySlug = new Map(programmeTypes.map((type) => [type.slug, type]));

/**
 * A summary for a programme that has not been given one by hand.
 *
 * Templated, but specific: it names the offering, its format and the area it
 * belongs to. Every value here is editable in the CMS, which is where editorial
 * polish belongs — this only has to be accurate and readable on day one.
 */
function summaryFor(title, type, area) {
  switch (type.slug) {
    case 'executive-certificate':
      return `An assessed executive certificate in ${title.replace(/^Advanced Certificate in /, '').toLowerCase()}, developed for senior professionals working in ${area.title.toLowerCase()}.`;
    case 'masterclass':
      return `A one-day executive masterclass on ${title.toLowerCase()}, led by senior practitioners and built around decisions you are accountable for.`;
    case 'short-course':
      return `A focused short course building practical capability in ${title.toLowerCase()}, for professionals working in ${area.title.toLowerCase()}.`;
    case 'advanced-executive-programme':
      return `The academy’s flagship programme for senior leaders and policymakers shaping ${area.title.toLowerCase()}.`;
    case 'executive-short-case':
      return `A short, decision-centred case: ${title.toLowerCase()}. Work the situation, commit to a decision, then compare it with what actually happened.`;
    default:
      return title;
  }
}

function outcomesFor(title, type, area) {
  switch (type.slug) {
    case 'executive-short-case':
      return [
        'Read a live situation quickly and identify what is actually being decided',
        'Weigh commercial, regulatory and reputational consequences together',
        'Commit to a defensible decision under incomplete information',
      ];
    case 'masterclass':
      return [
        `Apply current practice in ${title.toLowerCase()} to your own organisation`,
        'Recognise the risks that most often go unmanaged in this area',
        'Leave with a position you can take back to your leadership team',
      ];
    case 'short-course':
      return [
        `Work confidently with the core concepts of ${title.toLowerCase()}`,
        'Apply the material to a task you are responsible for',
        'Know where the common errors occur, and how to avoid them',
      ];
    default:
      return [
        `Set direction in ${area.title.toLowerCase()} with confidence`,
        'Evaluate risk, regulation and commercial opportunity together',
        'Lead change across teams, institutions and borders',
        'Defend your decisions to a board, a regulator or a market',
      ];
  }
}

const whoFor = (type) =>
  type.slug === 'advanced-executive-programme'
    ? 'Chief executives, board members, regulators, senior policymakers and directors responsible for strategy.'
    : type.slug === 'executive-certificate'
      ? 'Senior managers, directors, regulators and professionals seeking a formal executive qualification.'
      : type.slug === 'executive-short-case'
        ? 'Executives and managers who want decision practice rather than another lecture.'
        : 'Managers, specialists, entrepreneurs, policymakers and professionals working in the field.';

const lines = [];
const write = (line = '') => lines.push(line);

write('-- Module 06 — initial WEA catalogue.');
write('--');
write('-- Generated by scripts/generate-catalogue-seed.mjs from');
write('-- scripts/catalogue-data.mjs. Do not edit by hand: edit the data file and');
write('-- regenerate, or edit the content in the Super Admin CMS after deployment.');
write('--');
write('-- INSERT OR IGNORE against fixed ids, so re-applying is safe and never');
write('-- overwrites edits made through the CMS.');
write();

// --- Types -----------------------------------------------------------------
write('-- Programme types ---------------------------------------------------------');
programmeTypes.forEach((type, index) => {
  write(
    `INSERT OR IGNORE INTO programme_types (id, slug, title, plural_title, description, status, sort_order) VALUES (${[
      q(`type-${type.slug}`),
      q(type.slug),
      q(type.title),
      q(type.pluralTitle),
      q(type.description),
      q('PUBLISHED'),
      index + 1,
    ].join(', ')});`,
  );
});
write();

// --- Faculty ---------------------------------------------------------------
write('-- Faculty -----------------------------------------------------------------');
faculty.forEach((member, index) => {
  write(
    `INSERT OR IGNORE INTO faculty (id, slug, name, role_title, organisation, bio, expertise, image_url, status, sort_order) VALUES (${[
      q(`fac-${member.slug}`),
      q(member.slug),
      q(member.name),
      q(member.role),
      q(member.organisation),
      q(member.bio),
      q(JSON.stringify(member.expertise)),
      q(member.image),
      q('PUBLISHED'),
      index + 1,
    ].join(', ')});`,
  );
});
write();

// --- Payment ---------------------------------------------------------------
write('-- Payment methods ---------------------------------------------------------');
write(
  `INSERT OR IGNORE INTO payment_methods (id, slug, kind, title, instructions, bank_name, account_name, account_number, currency, reference_prefix, is_active, sort_order) VALUES (${[
    q('pay-bank-transfer'),
    q('bank-transfer'),
    q('BANK_TRANSFER'),
    q('Bank transfer'),
    q(
      'Transfer the tuition amount to the account below and quote your WEA registration reference exactly as shown. Your place is confirmed once payment is matched to the reference.',
    ),
    q('To be configured'),
    q('WUCO Executive Academy'),
    q('To be configured'),
    q('USD'),
    q('WEA'),
    1,
    1,
  ].join(', ')});`,
);
write(
  `INSERT OR IGNORE INTO payment_methods (id, slug, kind, title, instructions, currency, reference_prefix, is_active, sort_order) VALUES (${[
    q('pay-invoice'),
    q('invoice'),
    q('INVOICE'),
    q('Request an invoice'),
    q(
      'Request a formal invoice for your organisation. The programme office will issue it against your registration reference, normally within two working days.',
    ),
    q('USD'),
    q('WEA'),
    1,
    2,
  ].join(', ')});`,
);
write();

// --- Registration questions -------------------------------------------------
write('-- Global registration questions -------------------------------------------');
[
  {
    key: 'organisation',
    label: 'Organisation',
    type: 'TEXT',
    required: 1,
    help: 'The organisation you represent.',
  },
  {
    key: 'job_title',
    label: 'Job title',
    type: 'TEXT',
    required: 1,
    help: 'Your current role.',
  },
  {
    key: 'sector',
    label: 'Sector',
    type: 'SELECT',
    required: 0,
    help: '',
    options: [
      'Banking & financial services',
      'Government & public sector',
      'Retail & consumer markets',
      'Trade & investment',
      'Technology',
      'Legal & professional services',
      'Other',
    ],
  },
  {
    key: 'sponsorship',
    label: 'How will your place be funded?',
    type: 'SELECT',
    required: 0,
    help: '',
    options: ['Self-funded', 'Employer-sponsored', 'Government-sponsored', 'Undecided'],
  },
  {
    key: 'objectives',
    label: 'What do you want to get from this programme?',
    type: 'TEXTAREA',
    required: 0,
    help: 'A short note helps faculty tailor the sessions.',
  },
].forEach((field, index) => {
  write(
    `INSERT OR IGNORE INTO registration_fields (id, programme_id, field_key, label, field_type, options, help_text, required, sort_order) VALUES (${[
      q(`regfield-${field.key}`),
      'NULL',
      q(field.key),
      q(field.label),
      q(field.type),
      q(JSON.stringify(field.options ?? [])),
      q(field.help),
      field.required,
      index + 1,
    ].join(', ')});`,
  );
});
write();

// --- Areas, programmes, modules --------------------------------------------
let programmeCount = 0;
let moduleCount = 0;

areas.forEach((area, areaIndex) => {
  const areaId = `area-${area.slug}`;
  write(`-- ${area.code} ${area.title} `.padEnd(78, '-'));
  write(
    `INSERT OR IGNORE INTO programme_areas (id, slug, code, title, tagline, summary, description, image_url, status, sort_order) VALUES (${[
      q(areaId),
      q(area.slug),
      q(area.code),
      q(area.title),
      q(area.tagline),
      q(area.summary),
      q(area.description),
      q(area.image),
      q('PUBLISHED'),
      areaIndex + 1,
    ].join(', ')});`,
  );

  let orderInArea = 0;
  area.groups.forEach((group) => {
    const type = typeBySlug.get(group.type);
    if (!type) throw new Error(`Unknown programme type: ${group.type}`);

    group.items.forEach((title) => {
      orderInArea += 1;
      programmeCount += 1;
      const slug = slugify(title);
      const id = `prog-${slug}`;
      const flagship =
        type.slug === 'advanced-executive-programme' ||
        type.slug === 'executive-certificate';

      write(
        `INSERT OR IGNORE INTO programmes (id, slug, area_id, type_id, title, subtitle, summary, description, image_url, level, duration_label, delivery_mode, certificate_award, eligibility, who_should_attend, learning_outcomes, tuition_amount, tuition_currency, cpd_points, featured, status, sort_order) VALUES (${[
          q(id),
          q(slug),
          q(areaId),
          q(`type-${type.slug}`),
          q(title),
          q(area.tagline),
          q(summaryFor(title, type, area)),
          q(
            `${summaryFor(title, type, area)} Delivered by WUCO Executive Academy as part of ${area.title}, and backed by the institutional authority of the World United Consumer Organisation.`,
          ),
          q(area.image),
          q(type.defaults.level),
          q(type.defaults.duration),
          q(type.defaults.delivery),
          q(type.defaults.award),
          q(
            'Open to professionals with relevant working experience. No formal academic prerequisite.',
          ),
          q(whoFor(type)),
          q(JSON.stringify(outcomesFor(title, type, area))),
          type.defaults.tuition,
          q('USD'),
          type.defaults.cpd,
          flagship ? 1 : 0,
          q('PUBLISHED'),
          orderInArea,
        ].join(', ')});`,
      );

      // Module structures are seeded for the assessed formats only; a one-day
      // masterclass or a 90-minute case does not have a module tree.
      if (flagship && area.modules.length > 0) {
        area.modules.forEach((moduleTitle, moduleIndex) => {
          moduleCount += 1;
          write(
            `INSERT OR IGNORE INTO programme_modules (id, programme_id, number, title, summary, duration_label, sort_order) VALUES (${[
              q(`mod-${slug}-${moduleIndex + 1}`),
              q(id),
              moduleIndex + 1,
              q(moduleTitle),
              q(''),
              q(`${2 + (moduleIndex % 2)} weeks`),
              moduleIndex + 1,
            ].join(', ')});`,
          );
        });
      }

      (areaFaculty[area.slug] ?? []).forEach((facultySlug, facultyIndex) => {
        write(
          `INSERT OR IGNORE INTO programme_faculty (programme_id, faculty_id, role, sort_order) VALUES (${[
            q(id),
            q(`fac-${facultySlug}`),
            q(facultyIndex === 0 ? 'Programme Director' : 'Faculty'),
            facultyIndex + 1,
          ].join(', ')});`,
        );
      });
    });
  });
  write();
});

write(`-- Seeded ${areas.length} areas, ${programmeTypes.length} types, ${programmeCount} programmes, ${moduleCount} modules.`);
write();

writeFileSync(out, `${lines.join('\n')}\n`, 'utf8');
console.log(
  `Wrote ${out}\n  ${areas.length} areas, ${programmeTypes.length} types, ${programmeCount} programmes, ${moduleCount} modules, ${faculty.length} faculty.`,
);
