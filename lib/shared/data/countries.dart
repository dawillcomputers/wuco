/// The name for a stored code, or the code itself where it is not one we hold.
String countryName(String code) {
  final wanted = code.trim().toUpperCase();
  for (final country in weaCountries) {
    if (country.code == wanted) return country.name;
  }
  return code;
}

/// The code for whatever is stored, whether that is already a code or a name.
///
/// Registrations taken before this list existed hold free text, so a stored
/// "Nigeria" still resolves to NG rather than being dropped on the next edit.
String? countryCode(String value) {
  final wanted = value.trim().toLowerCase();
  if (wanted.isEmpty) return null;
  for (final country in weaCountries) {
    if (country.code.toLowerCase() == wanted) return country.code;
    if (country.name.toLowerCase() == wanted) return country.code;
  }
  return null;
}
